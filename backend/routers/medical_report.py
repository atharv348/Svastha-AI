    if cf.get("common_name"):
        story.append(Paragraph(f"<b>Common Name:</b> {cf['common_name']}", body))
    if cf.get("local_name_hindi"):
        story.append(Paragraph(f"<b>Hindi:</b> {cf['local_name_hindi']}", body))
    if cf.get("local_name_marathi"):
        story.append(Paragraph(f"<b>Marathi:</b> {cf['local_name_marathi']}", body))
