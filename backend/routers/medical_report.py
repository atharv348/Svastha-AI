def _build_dashboard_pdf(buffer, report_data):
    from reportlab.lib.pagesizes import A4
    from reportlab.lib import colors
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, HRFlowable
    from reportlab.lib.units import inch
    from reportlab.lib.enums import TA_CENTER, TA_LEFT

    doc = SimpleDocTemplate(buffer, pagesize=A4, rightMargin=50, leftMargin=50, topMargin=40, bottomMargin=40)
    styles = getSampleStyleSheet()
    teal = colors.HexColor("#0D9488")
    dark = colors.HexColor("#0F172A")
    muted = colors.HexColor("#64748B")
    light_bg = colors.HexColor("#F8FAFC")

    title_style = ParagraphStyle("Title", parent=styles["Heading1"], fontSize=24, alignment=TA_CENTER, textColor=teal, fontName="Helvetica-Bold")
    subtitle_style = ParagraphStyle("Sub", parent=styles["Normal"], fontSize=12, alignment=TA_CENTER, textColor=muted, spaceAfter=20)
    section_h = ParagraphStyle("Sec", parent=styles["Heading2"], fontSize=14, spaceBefore=15, spaceAfter=10, textColor=dark, fontName="Helvetica-Bold")
    body = ParagraphStyle("Body", parent=styles["Normal"], fontSize=10, leading=14)

    story = []
    story.append(Paragraph("SvasthaAI", title_style))
    story.append(Paragraph(report_data["report_header"]["title"], subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1, color=teal, spaceAfter=20))

    # Patient/User Info
    pi = report_data["patient_info"]
    info_data = [
        ["User Name", pi["name"], "Goal", pi["fitness_goal"]],
        ["User ID", pi["patient_id"], "Streak", pi["streak"]],
        ["Age", str(pi["age"] or "N/A"), "Generated", report_data["report_header"]["generated_at"]]
    ]
    it = Table(info_data, colWidths=[1.2*inch, 2*inch, 1.2*inch, 2*inch])
    it.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), light_bg),
        ("BACKGROUND", (2, 0), (2, -1), light_bg),
        ("GRID", (0,0), (-1,-1), 0.5, colors.grey),
        ("FONTSIZE", (0,0), (-1,-1), 9),
        ("VALIGN", (0,0), (-1,-1), 'MIDDLE'),
        ("LEFTPADDING", (0,0), (-1,-1), 6),
    ]))
    story.append(Paragraph("User Profile Overview", section_h))
    story.append(it)

    # Vitals
    story.append(Paragraph("Key Vital Metrics", section_h))
    vitals_data = [["Metric", "Value", "Status"]]
    for m in report_data["vital_metrics"]:
        vitals_data.append([m["label"], m["value"], m["status"]])
    vt = Table(vitals_data, colWidths=[2.2*inch, 2.2*inch, 2*inch])
    vt.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,0), teal),
        ("TEXTCOLOR", (0,0), (-1,0), colors.white),
        ("GRID", (0,0), (-1,-1), 0.5, colors.grey),
        ("FONTNAME", (0,0), (-1,0), "Helvetica-Bold"),
        ("ALIGN", (0,0), (-1,-1), "CENTER"),
        ("VALIGN", (0,0), (-1,-1), 'MIDDLE'),
        ("TOPPADDING", (0,0), (-1,-1), 8),
        ("BOTTOMPADDING", (0,0), (-1,-1), 8),
    ]))
    story.append(vt)

    # Recent Scans
    if report_data["recent_activity"]:
        story.append(Paragraph("Recent AI Diagnostic Scans", section_h))
        scan_data = [["Diagnostic Result", "Date", "Confidence"]]
        for s in report_data["recent_activity"]:
            scan_data.append([s["title"], s["date"], s["result"]])
        st = Table(scan_data, colWidths=[3*inch, 1.7*inch, 1.7*inch])
        st.setStyle(TableStyle([
            ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#0284C7")),
            ("TEXTCOLOR", (0,0), (-1,0), colors.white),
            ("GRID", (0,0), (-1,-1), 0.5, colors.grey),
            ("VALIGN", (0,0), (-1,-1), 'MIDDLE'),
        ]))
        story.append(st)

    # Insights
    story.append(Paragraph("AI Intelligence Insights", section_h))
    for ins in report_data["ai_insights"]:
        story.append(Paragraph(f"• {ins}", body))
        story.append(Spacer(1, 6))

    story.append(Spacer(1, 30))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.grey))
    story.append(Paragraph(report_data["disclaimer"], ParagraphStyle("Disc", parent=styles["Normal"], fontSize=8, textColor=muted, alignment=TA_CENTER)))

    doc.build(story)
    buffer.seek(0)

