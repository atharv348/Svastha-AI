def _get_risk_color_hex(risk_level: str) -> str:
    """Return HEX color for risk level."""
    mapping = {
        "CRITICAL": "#DC2626",
        "HIGH": "#EA580C",
        "MODERATE": "#CA8A04",
        "LOW": "#16A34A",
    }
    return mapping.get(risk_level.upper(), "#6B7280")


def _get_priority_label(priority: str) -> str:
    mapping = {
        "critical": "CRITICAL",
        "high": "HIGH",
        "medium": "MODERATE",
        "low": "LOW",
    }
    return mapping.get(priority, "LOW")


def _build_comprehensive_report_data(prediction: Prediction, user: User) -> dict:
    """Build a comprehensive JSON report from a prediction record."""
    body_part = prediction.body_part or "skin"
    predicted_class = prediction.predicted_class or "unknown"
    disease_data = BODY_PART_DISEASES.get(body_part, {}).get(predicted_class, {})

    scan_type_map = {
        "skin": "Dermoscopic Imaging",
        "eye": "Fundus / Retinal Imaging",
        "oral": "Intraoral Clinical Imaging",
        "bone": "Radiographic X-Ray",
        "lungs": "Chest Radiograph (PA View)",
        "muac": "MUAC Anthropometric Assessment",
    }

    risk_label = _get_priority_label(prediction.priority or "low")

    patient_info = {
        "name": user.full_name or user.username,
        "patient_id": f"SVA-{user.id:06d}",
        "age": getattr(user, "age", None),
        "gender": getattr(user, "gender", None),
        "report_date": prediction.created_at.strftime("%B %d, %Y") if prediction.created_at else datetime.now().strftime("%B %d, %Y"),
        "report_time": prediction.created_at.strftime("%I:%M %p") if prediction.created_at else datetime.now().strftime("%I:%M %p"),
        "report_id": f"RPT-{prediction.id:08d}",
    }

    scan_details = {
        "body_region": body_part.capitalize(),
        "scan_type": scan_type_map.get(body_part, "Clinical Imaging"),
        "modality": "AI-Assisted Computer Vision Analysis",
        "scan_date": prediction.created_at.strftime("%Y-%m-%d") if prediction.created_at else datetime.now().strftime("%Y-%m-%d"),
    }

    clinical_findings = {
        "primary_diagnosis": disease_data.get("scientific", prediction.predicted_name or "Unknown"),
        "common_name": disease_data.get("common", ""),
        "local_name_hindi": disease_data.get("hindi", ""),
        "local_name_marathi": disease_data.get("marathi", ""),
        "confidence_score": round((prediction.confidence or 0) * 100, 1),
        "risk_level": risk_label,
        "clinical_description": disease_data.get("what_it_means", "Requires further clinical evaluation."),
        "specialist_referral": disease_data.get("specialist", "General Physician"),
    }

    care_plan = {
        "immediate_actions": disease_data.get("immediate_actions", []),
        "monitoring_signs": disease_data.get("watch_for_signs", []),
        "questions_for_doctor": disease_data.get("ask_doctor", []),
    }

    ai_summary = prediction.ai_advice or "AI analysis summary is not available for this report."

    return {
        "report_header": {
            "title": "SvasthaAI Medical Diagnostic Report",
            "subtitle": "AI-Assisted Clinical Analysis",
            "institution": "SvasthaAI Health Intelligence Platform",
            "report_id": patient_info["report_id"],
            "generated_at": datetime.now().strftime("%B %d, %Y at %I:%M %p"),
        },
        "patient_info": patient_info,
        "scan_details": scan_details,
        "clinical_findings": clinical_findings,
        "care_plan": care_plan,
        "ai_analysis_summary": ai_summary,
        "model_metrics": {
            "body_part": body_part,
            "diagnostic_confidence": clinical_findings["confidence_score"],
        },
        "disclaimer": (
            "IMPORTANT DISCLAIMER: This report is generated by an AI-powered diagnostic assistance system "
            "and is intended for informational and screening purposes only. It does NOT constitute a medical "
            "diagnosis, medical advice, or a substitute for professional clinical judgment. The results should "
            "be reviewed and confirmed by a qualified healthcare professional. SvasthaAI and its developers "
            "assume no liability for clinical decisions made based on this report. Always consult your doctor "
            "before starting or changing any treatment."
        ),
    }


@router.get("/json/{prediction_id}")
def get_report_json(
    prediction_id: int,
    current_user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """Return comprehensive medical report as JSON for frontend rendering."""
    prediction = (
        db.query(Prediction)
        .filter(Prediction.id == prediction_id, Prediction.user_id == current_user.id)
        .first()
    )
    if not prediction:
        raise HTTPException(status_code=404, detail="Prediction not found")

    return _build_comprehensive_report_data(prediction, current_user)


@router.get("/pdf/{prediction_id}")
def download_report_pdf(
    prediction_id: int,
    token: Optional[str] = None,
    current_user: Optional[User] = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """
    Generate and download a professional PDF medical report.
    NEW VERSION: Supports both token query param and Authorization header.
    """
    import logging
    import io
    from fastapi.responses import StreamingResponse

    logger = logging.getLogger("uvicorn.error")
    logger.info(f"PDF Download Request for Prediction ID: {prediction_id}")

    # Use current_user if available (from header), otherwise verify token from query param
    user = current_user
    if not user and token:
        from services.auth import verify_token
        username = verify_token(token)
        if username:
            user = db.query(User).filter(User.username == username).first()

    if not user:
        logger.error("Authentication failed for PDF download")
        raise HTTPException(status_code=401, detail="Authentication required")

    try:
        prediction = (
            db.query(Prediction)
            .filter(Prediction.id == prediction_id, Prediction.user_id == user.id)
            .first()
        )
        if not prediction:
            logger.error(f"Prediction {prediction_id} not found for user {user.id}")
            raise HTTPException(status_code=404, detail="Prediction not found")

        # Build data
        report_data = _build_comprehensive_report_data(prediction, user)
        
        # Generate PDF
        pdf_buffer = io.BytesIO()
        _build_pdf(pdf_buffer, report_data)
        pdf_buffer.seek(0)

        filename = f"SvasthaAI_Report_{prediction_id}.pdf"
        
        return StreamingResponse(
            pdf_buffer,
            media_type="application/pdf",
            headers={
                "Content-Disposition": f'attachment; filename="{filename}"',
                "Access-Control-Expose-Headers": "Content-Disposition"
            }
        )

    except Exception as e:
        logger.error(f"Error generating PDF: {str(e)}")
        import traceback
        logger.error(traceback.format_exc())
        raise HTTPException(status_code=500, detail=f"PDF Generation failed: {str(e)}")


