    if cp.get("monitoring_signs"):
        story.append(Paragraph("<b>Signs to Monitor:</b>", body))
        for sign in cp["monitoring_signs"]:
            story.append(Paragraph(f"▲ {sign}", bullet_style))
        story.append(Spacer(1, 6))

    # Questions for Doctor
    if cp.get("questions_for_doctor"):
        story.append(Paragraph("<b>Questions to Ask Your Doctor:</b>", body))
        for q in cp["questions_for_doctor"]:
            story.append(Paragraph(f"? {q}", bullet_style))
        story.append(Spacer(1, 10))

