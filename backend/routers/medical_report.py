    if cp.get("immediate_actions"):
        story.append(Paragraph("<b>Immediate Actions:</b>", body))
        for action in cp["immediate_actions"]:
            story.append(Paragraph(f"● {action}", bullet_style))
        story.append(Spacer(1, 6))

