    ai_clean = ai_text.replace("**", "").replace("##", "").replace("# ", "")
    for para in ai_clean.split("\n\n"):
        if para.strip():
            story.append(Paragraph(para.strip(), body))
            story.append(Spacer(1, 4))
    story.append(Spacer(1, 8))

